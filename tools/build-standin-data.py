def table_columns(sql_text, table):
    """Column names of a CREATE TABLE statement in instawdbdw.sql, in order."""
    match = re.search(r"CREATE TABLE \[dbo\]\.\[%s\]\((.*?)\n\)" % table, sql_text, re.S)
    if not match:
        raise SystemExit(f"CREATE TABLE for {table} not found in instawdbdw.sql")
    return re.findall(r"^\s*\[(\w+)\]\s+\[", match.group(1), re.M)


def is_number(value):
    try:
        float(value)
        return True
    except ValueError:
        return False


def convert_aw_table(source_dir, sql_text, table):
    """Reads a headerless pipe-delimited AdventureWorksDW file and returns (header, rows) ready for CSV."""
    columns = table_columns(sql_text, table)
    with open(source_dir / f"{table}.csv", encoding="utf-8", newline="") as handle:
        rows = [row for row in csv.reader(handle, delimiter="|", quoting=csv.QUOTE_NONE) if row]
    bad = [i for i, row in enumerate(rows) if len(row) != len(columns)]
    if bad:
        raise SystemExit(f"{table}: {len(bad)} rows don't have {len(columns)} fields (first bad row {bad[0]})")

    keep, fill = [], set()
    for index, name in enumerate(columns):
        if name in DROP_COLUMNS.get(table, set()):
            continue
        values = [row[index] for row in rows]
        empty = sum(1 for v in values if v == "")
        numeric = all(v == "" or is_number(v) for v in values)
        if not numeric and empty:
            if empty / len(values) > SPARSE_THRESHOLD:
                continue  # mostly-empty text column (for example Title, AddressLine2): drop it
            fill.add(index)
        keep.append(index)

    header = [columns[i] for i in keep]
    out = [[("Unknown" if (i in fill and row[i] == "") else row[i]) for i in keep] for row in rows]
    return header, out


def churn_rows(rng, count=2500):
    """Synthetic Litware customers. Month-to-month contracts, short tenure, and many support tickets churn more."""
    contracts = [("Month-to-month", 0.55, 0.42), ("One year", 0.27, 0.14), ("Two year", 0.18, 0.05)]
    regions = ["North America", "Europe", "Pacific"]
    payments = ["Credit card", "Bank transfer", "Digital wallet", "Gift card"]
    categories = ["Bikes", "Components", "Clothing", "Accessories"]
    header = ["CustomerID", "Gender", "Age", "Region", "Tenure", "StoreContract", "PaymentMethod",
              "PaperlessBilling", "SupportTickets", "LastPurchaseCategory", "TotalAmount", "Churn"]
    rows = []
    for n in range(count):
        contract, _, base_churn = rng.choices(contracts, weights=[c[1] for c in contracts])[0]
        tenure = rng.randint(1, 12) if contract == "Month-to-month" and rng.random() < 0.6 else rng.randint(1, 72)
        tickets = min(9, int(rng.expovariate(0.6)))
        p_churn = base_churn + (0.15 if tenure <= 6 else 0) + 0.04 * tickets - (0.1 if tenure > 36 else 0)
        churn = "Yes" if rng.random() < max(0.02, min(0.9, p_churn)) else "No"
        rows.append([
            f"LW{n + 10001:06d}", rng.choice(["Female", "Male"]), rng.randint(18, 75), rng.choice(regions), tenure,
            contract, rng.choice(payments), rng.choice(["Yes", "No"]), tickets, rng.choice(categories),
            f"{rng.uniform(20, 150):.2f}", churn,
        ])
    return header, rows


def bounce_rows(rng):
    """Synthetic web analytics. Millennials on mobile with unmatched or unavailable products bounce the most."""
    header = ["CustomerGeneration", "CustomerSentiment", "DeviceType", "ProductAvailability", "ProductCategory",
              "ProductMatch", "Number_of_times_products_searches_did_not_matched",
              "total_number_of_time_products_searches", "Website_Bounce_rate", "Website_visitors", "SemanticModel_key"]
    generations = {"Millennials": 0.18, "Gen Z": 0.10, "Gen X": 0.04, "Baby Boomers": 0.02}
    sentiments = {"Happy": -0.04, "Neutral": 0.0, "Unhappy": 0.08}
    devices = {"Mobile": 0.10, "Tablet": 0.05, "Desktop": 0.0}
    categories = ["Accessories", "Bikes", "Clothing", "Components"]
    rows = []
    for generation, g in generations.items():
        for sentiment, s in sentiments.items():
            for device, d in devices.items():
                for availability in ("Yes", "No"):
                    for key, category in enumerate(categories, start=1):
                        for match in ("Yes", "No"):
                            searches = rng.randint(1500, 6000)
                            unmatched = int(searches * (rng.uniform(0.35, 0.6) if match == "No" else rng.uniform(0.05, 0.2)))
                            rate = 0.08 + g + s + d + (0.08 if availability == "No" else 0) + (0.07 if match == "No" else 0)
                            rate = round(min(0.95, max(0.02, rate + rng.uniform(-0.03, 0.03))), 2)
                            visitors = int(searches * rng.uniform(1.8, 2.6))
                            rows.append([generation, sentiment, device, availability, category, match,
                                         unmatched, searches, rate, visitors, key])
    return header, rows


def to_csv_bytes(header, rows):
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buffer.getvalue().encode("utf-8")


def check_no_mixed_text(name, header, rows):
    """Fails if a non-numeric column has empty values (pandas would read them as NaN and Spark would reject the mix)."""
    for index, column in enumerate(header):
        values = [str(row[index]) for row in rows]
        if any(v == "" for v in values) and not all(v == "" or is_number(v) for v in values):
            raise SystemExit(f"{name}: text column {column} still has empty values")


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    source_dir, output = Path(sys.argv[1]), Path(sys.argv[2])
    sql_text = (source_dir / "instawdbdw.sql").read_text(encoding="utf-8", errors="replace")
    rng = random.Random(560)

    files = {}
    for table, file_name in AW_TABLES.items():
        files[file_name] = convert_aw_table(source_dir, sql_text, table)
    files["CustomerChurnData.csv"] = churn_rows(rng)
    files["website_bounce_rate.csv"] = bounce_rows(rng)

    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for file_name, (header, rows) in sorted(files.items()):
            check_no_mixed_text(file_name, header, rows)
            info = zipfile.ZipInfo(f"litwaredata/{file_name}", date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, to_csv_bytes(header, rows))
            print(f"{file_name:28} {len(rows):>7} rows  {len(header):>3} columns")
        notice = zipfile.ZipInfo("litwaredata/NOTICE.txt", date_time=(2026, 1, 1, 0, 0, 0))
        notice.compress_type = zipfile.ZIP_DEFLATED
        archive.writestr(notice, AW_NOTICE)
    print(f"wrote {output} ({output.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
